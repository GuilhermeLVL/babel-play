export const LEXICOS: Readonly<Record<'pt' | 'en' | 'es', Lexico>> = { pt: PT, en: EN, es: ES };

const uniao = (f: (l: Lexico) => readonly string[]) => [...new Set([PT, EN, ES].flatMap(f))];

/** Idioma desconhecido: só os verbos e os pronomes (as pistas de estrutura), nunca as palavras de emoção. */
const GENERICO: Lexico = {
  verbos: uniao((l) => l.verbos),
  gritos: uniao((l) => l.gritos),
  sussurros: uniao((l) => l.sussurros),
  palavras: { feliz: ['haha', 'jaja'], triste: [], bravo: [], surpreso: [], relaxado: ['shh'] },
  pronomes: [],
};

/** O léxico do idioma (`pt-BR` → `pt`); idioma fora de pt/en/es recebe o genérico. */
export function lexicoDoIdioma(idioma?: string): Lexico {
  const base = (idioma ?? '').slice(0, 2).toLowerCase();
  return base === 'pt' || base === 'en' || base === 'es' ? LEXICOS[base] : GENERICO;
}
